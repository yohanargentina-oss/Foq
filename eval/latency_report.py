"""
Render eval/LATENCY.md from eval/results/latency.json.
No number is typed by hand.

    python eval/latency_report.py
"""

import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES = os.path.join(ROOT, "eval", "results")


LAT_NAMES = {"bare": "Foq 8B, no adapter", "lora": "Foq 8B + adapter v1"}


def latency_section():
    path = os.path.join(RES, "latency.json")
    if not os.path.exists(path):
        return []
    r = json.load(open(path, encoding="utf-8"))
    any_pass = next(iter(r["configs"].values()))["passes"][0]
    gpu = any_pass["gpu_before_start"]
    out = ["## Latency of one decision (Foq, local GPU)", "",
           f"Generated by `python eval/latency.py` on {r['measured_at']}: {r['cases']} `exam_test` cases, "
           f"{r['method']}. GPU: {gpu.get('name')} (driver {gpu.get('driver')}), {r['machine']['os']}. "
           "Server time is what llama-server reports; the HTTP round trip is what a Python client on the "
           "same machine waits for.", "",
           "| Configuration | Server median | Server P95 | HTTP median | HTTP P95 | Passes (HTTP median each) | Accuracy check |",
           "|---|---|---|---|---|---|---|"]
    for tag, c in r["configs"].items():
        s, h = c["pooled_server_ms"], c["pooled_http_round_trip_ms"]
        each = ", ".join(f"{p['http_round_trip_ms']['median']}" for p in c["passes"])
        acc = ", ".join(f"{p['accuracy_check_pct']} %" for p in c["passes"])
        out.append(f"| {LAT_NAMES.get(tag, tag)} | {s['median']} ms | {s['p95']} ms | {h['median']} ms | "
                   f"{h['p95']} ms | {each} ms | {acc} |")
    return out + [""]


def main():
    out = ["# Foq — decision latency", "",
           "Generated by `python eval/latency_report.py`. Rerun `eval/latency.py` "
           "to reproduce every number.", ""] + latency_section()
    with open(os.path.join(ROOT, "eval", "LATENCY.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("-> eval/LATENCY.md")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
