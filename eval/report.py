"""
Render eval/RESULTS.md from eval/results/calibration_*.json. No number is typed by hand.

    python eval/report.py
"""

import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
RES = os.path.join(ROOT, "eval", "results")
CONFIGS = [("bare", "Foq 8B, no adapter (`NO_LORA=1`, or adapter not installed)"),
           ("lora", "Foq 8B + LoRA decision adapter v1 (default when `foq setup` installed it)")]


def ci(x):
    return f"[{x[0]}–{x[1]}]" if x and x[0] is not None else "n/a"


def main():
    out = ["# Foq — held-out exam and calibration results", "",
           "Generated by `python eval/report.py` from `eval/results/calibration_*.json`. "
           "Rerun the pipeline in `eval/README.md` to reproduce every number.", ""]
    for tag, label in CONFIGS:
        path = os.path.join(RES, f"calibration_{tag}.json")
        if not os.path.exists(path):
            continue
        r = json.load(open(path, encoding="utf-8"))
        ev = r["on_exam_test"]
        out += [f"## {label}", "",
                f"Temperature fitted on `calib_val` ({r['fit_set']['n']} cases): **T = {r['temperature_fitted']}**"
                + (" (at search bound!)" if r["temperature_fit_at_search_bound"] else "")
                + f". Everything below is measured on `exam_test` ({r['eval_set']['n']} cases, never used for fitting).", "",
                "| Temperature | Accuracy [95 % CI] | Mean confidence | ECE (15 bins) [95 % CI] | Brier | NLL |",
                "|---|---|---|---|---|---|"]
        names = {"raw_T1": "1 (raw)", "old_profile": "0.1 (profile shipped in 1.0.5)", "fitted": "fitted"}
        for k, v in ev.items():
            out.append(f"| {names[k]} = {v['temperature']} | {v['accuracy_pct']} % {ci(v['accuracy_ci95_pct'])} | "
                       f"{v['mean_confidence_pct']} % | {v['ece_pct']} % {ci(v['ece_ci95_pct'])} | {v['brier']} | {v['nll']} |")
        out += ["", "**What `needs_review` does** (decisions below the threshold are flagged for review):", "",
                "| Threshold | T | Sent to review | Accuracy on kept decisions [95 % CI] | Errors caught |",
                "|---|---|---|---|---|"]
        for k in ("old_profile", "fitted"):
            for x in ev[k]["needs_review"]:
                kept = (f"{x['accuracy_on_kept_pct']} % {ci(x['accuracy_on_kept_ci95_pct'])}"
                        if x["kept"] else "none kept")
                out.append(f"| {x['threshold']} | {ev[k]['temperature']} | {x['review_share_pct']} % | "
                           f"{kept} ({x['kept']} kept) | {x['errors_caught_pct']} % |")
        g = r["on_exam_test_by_group_fitted_T"]
        out += ["", "By task family (fitted T):", "",
                "| Family | Cases | Accuracy [95 % CI] | ECE |", "|---|---|---|---|"]
        for k, v in g.items():
            out.append(f"| {k.replace('_', ' ')} | {v['n']} | {v['accuracy_pct']} % {ci(v['accuracy_ci95_pct'])} | {v['ece_pct']} % |")
        d = r["on_exam_test_detail_fitted_T"]
        out += ["", "High confidence (fitted T): how often Foq is right when it is very sure:", "",
                "| Confidence at least | Decisions | Correct | Accuracy [95 % CI] |", "|---|---|---|---|"]
        for x in d["high_confidence"]:
            acc = (f"{x['correct'] / x['decisions'] * 100:.1f} % {ci(x['accuracy_ci95_pct'])}"
                   if x["decisions"] else "n/a")
            out.append(f"| {x['min_confidence']} | {x['decisions']} | {x['correct']} | {acc} |")
        th = d["default_threshold"]
        out += ["", f"By category (fitted T; \"kept\" = confidence >= {th}, the default `needs_review` threshold):", "",
                "| Category | Cases | Accuracy | Kept | Correct among kept | Accuracy on kept |",
                "|---|---|---|---|---|---|"]
        for c, x in d["per_category"].items():
            ak = f"{x['accuracy_on_kept_pct']} %" if x["accuracy_on_kept_pct"] is not None else "n/a"
            out.append(f"| {c.replace('_', ' ')} | {x['n']} | {x['accuracy_pct']} % | "
                       f"{x['kept_at_default_threshold']} | {x['correct_kept']} | {ak} |")
        out.append("")
    with open(os.path.join(ROOT, "eval", "RESULTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("-> eval/RESULTS.md")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
